var createError = require('http-errors');
var express = require('express');
var path = require('path');
var cookieParser = require('cookie-parser');
var logger = require('morgan');
const cors = require('cors');
const UserControllerPayment = require("./controller/client_controllers/payment")

// const  client_Routes= 

var app = express();
app.use(cors());

// view engine setup
app.set('views', path.join(__dirname, 'views'));
app.set('view engine', 'jade');

app.use(logger('dev'));

app.post('/webhook', express.raw({ type: 'application/json' }), UserControllerPayment.webhook);

app.use(express.json());
app.use(express.urlencoded({ extended: true }));
app.use(cookieParser());
app.use(express.static(path.join(__dirname, 'public')));

app.use('/client',require('./routes/client_module/client_routes') );
app.use('/coach',require('./routes/coach_module/coach_routes') );
app.use('/admin',require('./routes/admin_module/admin_routes') );
app.use('/customerSupport',require('./routes/support_module/support_routes') );

// catch 404 and forward to error handler
app.use(function(req, res, next) {
  next(createError(404));
});
// error handler
app.use(function(err, req, res, next) {
  // set locals, only providing error in development
  res.locals.message = err.message;
  res.locals.error = req.app.get('env') === 'development' ? err : {};

  // render the error page
  res.status(err.status || 500);
  res.render('error');
});

module.exports = app;
